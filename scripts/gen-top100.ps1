# Generates internal/mods/top_data.go from the VS Code Marketplace top-100 by installs.
$ErrorActionPreference = 'Stop'

$headers = @{
  'Accept'     = 'application/json;api-version=7.1-preview.1'
  'User-Agent' = 'NeoMind/0.4.0'
}
$body = '{"filters":[{"criteria":[{"filterType":8,"value":"Microsoft.VisualStudio.Code"}],"pageNumber":1,"pageSize":100,"sortBy":4,"sortOrder":0}],"flags":918}'

Write-Host '==> fetching top 100 extensions from the VS Code Marketplace'
$response = Invoke-RestMethod -Uri 'https://marketplace.visualstudio.com/_apis/public/gallery/extensionquery' `
  -Method Post -Body $body -ContentType 'application/json' -Headers $headers -TimeoutSec 60
$extensions = $response.results[0].extensions
if ($extensions.Count -lt 100) { throw "Expected 100 extensions, got $($extensions.Count)" }

function GoStr($value) {
  if ($null -eq $value) { return '""' }
  $s = [string]$value
  $s = $s -replace '\\', '\\' -replace '"', '\"' -replace "`r", '' -replace "`n", '\n' -replace "`t", '\t'
  return '"' + $s + '"'
}

function Prop($ext, $key) {
  $p = $ext.versions[0].properties | Where-Object { $_.key -eq $key } | Select-Object -First 1
  if ($p) { return [string]$p.value }
  return ''
}

function Stat($ext, $name) {
  $s = $ext.statistics | Where-Object { $_.statisticName -eq $name } | Select-Object -First 1
  if ($s) { return [double]$s.value }
  return 0
}

$lines = @()
$lines += '// Code generated by scripts/gen-top100.ps1 from the VS Code Marketplace. DO NOT EDIT.'
$lines += '// These are reference cards only: NeoMind never downloads or installs any extension.'
$lines += ''
$lines += 'package mods'
$lines += ''
$lines += '// MarketplaceMod is one top extension shown in the VS Code-style catalog.'
$lines += 'type MarketplaceMod struct {'
$lines += '	ID           string  `json:"id"`'
$lines += '	Name         string  `json:"name"`'
$lines += '	Publisher    string  `json:"publisher"`'
$lines += '	Description  string  `json:"description"`'
$lines += '	Icon         string  `json:"icon"`'
$lines += '	Source       string  `json:"source"`'
$lines += '	Marketplace  string  `json:"marketplace"`'
$lines += '	Installs     int64   `json:"installs"`'
$lines += '	Rating       float64 `json:"rating"`'
$lines += '	RatingCount  int64   `json:"ratingCount"`'
$lines += '	ExecutesCode bool    `json:"executesCode"`'
$lines += '}'
$lines += ''
$lines += '// TopCatalog is the 100 most installed VS Code extensions at generation time.'
$lines += 'var TopCatalog = []MarketplaceMod{'

$i = 0
foreach ($ext in $extensions) {
  $i++
  $id = "$($ext.publisher.publisherName).$($ext.extensionName)"
  $name = [string]$ext.displayName
  if ([string]::IsNullOrWhiteSpace($name)) { $name = [string]$ext.extensionName }

  $publisher = [string]$ext.publisher.displayName
  if ([string]::IsNullOrWhiteSpace($publisher)) { $publisher = [string]$ext.publisher.publisherName }

  $description = [string]$ext.shortDescription
  if ($description.Length -gt 180) { $description = $description.Substring(0, 177) + '...' }
  $description = $description -replace '[^\x20-\x7E\u00A0-\uFFFF]', ' '

  $icon = ''
  $iconFile = $ext.versions[0].files | Where-Object { $_.assetType -eq 'Microsoft.VisualStudio.Services.Icons.Default' } | Select-Object -First 1
  if ($iconFile) { $icon = [string]$iconFile.source }

  $source = Prop $ext 'Microsoft.VisualStudio.Services.Links.Source'
  if (-not $source) { $source = Prop $ext 'Microsoft.VisualStudio.Services.Links.GitHub' }
  if (-not $source) { $source = Prop $ext 'Microsoft.VisualStudio.Services.Links.Learn' }
  if ($source -and $source -notmatch '^https://') { $source = '' }

  $marketplace = "https://marketplace.visualstudio.com/items?itemName=$id"
  $installs = [int64](Stat $ext 'install')
  $rating = [math]::Round((Stat $ext 'weightedRating'), 2)
  $ratingCount = [int64](Stat $ext 'ratingcount')
  $executes = ((Prop $ext 'Microsoft.VisualStudio.Code.ExecutesCode') -eq 'true')

  $lines += '	{'
  $lines += "		ID: $(GoStr $id),"
  $lines += "		Name: $(GoStr $name),"
  $lines += "		Publisher: $(GoStr $publisher),"
  $lines += "		Description: $(GoStr $description),"
  $lines += "		Icon: $(GoStr $icon),"
  $lines += "		Source: $(GoStr $source),"
  $lines += "		Marketplace: $(GoStr $marketplace),"
  $lines += "		Installs: $installs,"
  $lines += "		Rating: $rating,"
  $lines += "		RatingCount: $ratingCount,"
  $lines += "		ExecutesCode: $($executes.ToString().ToLower()),"
  $lines += '	},'
}
$lines += '}'
$lines += ''

$target = Join-Path $PSScriptRoot '..\internal\mods\top_data.go'
$lines -join "`n" | Set-Content -Path $target -Encoding UTF8
Write-Host "==> wrote $i entries to $target"
